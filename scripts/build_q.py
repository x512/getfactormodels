# scripts/build_q_registry.py
"""Generate the registry mappings for Q-Global's Anomalies.

Scrapes anomaly identifiers and names from the global-q testing portfolios
page and saves the parsed mappings into a generated Python file.
"""
import html
import re
import urllib.request
from pathlib import Path

URL = "https://global-q.org/testingportfolios.html"
OUT_PATH = Path("src/getfactormodels/registry/_q.py")

HEADER = f"""# AUTO-GENERATED by scripts/build_q_registry.py. Do not edit.
#
# Source Data Attribution: {URL}
# Terms of Use: Academic and non-commercial research use only (Global-q.org).
"""


def _scrape() -> str:
    print(f"  [Q] Downloading {URL}...")
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=10) as response:
        raw_html = response.read().decode("utf-8")

    # Clean the raw HTML into a single flat string
    text = html.unescape(raw_html)
    text = re.sub(r"<[^>]+>", " ", text)
    return re.sub(r"\s+", " ", text)


def _parse(text: str) -> dict[str, dict[str, str]]:
    # Truncate before footer begins (was capturing all footer text in tv_1)
    cutoff = text.find("References Hou")
    if cutoff != -1:
        text = text[:cutoff]

    category_pat = re.compile(r"([a-zA-Z\-]+)\s+Zip folders", re.IGNORECASE)
    anomaly_pat = re.compile(r'\(\s*"([^"]+)"\s*\)\s*,\s*([^;]+)')

    matches = list(category_pat.finditer(text))
    if not matches:
        raise ValueError("Could not find any category headers in the HTML.")

    registry: dict[str, dict[str, str]] = {}
    
    for i, match in enumerate(matches):
        start = match.end()
        # Since `text` is now truncated, this len(text) is safe.
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        
        category = match.group(1).lower()
        block = text[start:end]
        
        anomalies = {
            m.group(1).strip(): m.group(2).strip().rstrip(".;")
            for m in anomaly_pat.finditer(block)
        }
        
        if anomalies:
            registry[category] = anomalies

    return registry

def _render(registry: dict[str, dict[str, str]]) -> str:
    # flatten all anomalies across all categories
    all_anomalies = {k: v for anoms in registry.values() for k, v in anoms.items()}
    anomaly_lines = [
        f'    "{k}": {{"name": {v!r}}},' 
        for k, v in sorted(all_anomalies.items())
    ]
    anomalies_str = "\n".join(anomaly_lines)

    # themes
    theme_lines = [
        f'    "{cat}": {{"name": {cat.replace("-", " ").title()!r}}},' 
        for cat in sorted(registry.keys())
    ]
    themes_str = "\n".join(theme_lines)

    # tuples, not frozensets, theme factors 
    theme_factor_lines = []
    for category, anomalies_dict in sorted(registry.items()):
        sorted_anoms = sorted(anomalies_dict.keys())
        chunks = [
            "        " + ", ".join(f'"{a}"' for a in sorted_anoms[i:i + 6]) + ","
            for i in range(0, len(sorted_anoms), 6)
        ]
        theme_factor_lines.append(
            f'    "{category}": (\n' + "\n".join(chunks) + "\n    ),"
        )
    theme_factors_str = "\n".join(theme_factor_lines)

    return (
        HEADER
        + f"\nQ_ANOMALIES = {{\n{anomalies_str}\n}}\n"
        + f"\nQ_THEMES = {{\n{themes_str}\n}}\n"
        + f"\nQ_THEME_FACTORS = {{\n{theme_factors_str}\n}}\n"
    )


def main() -> None:
    text = _scrape()
    registry = _parse(text)
    content = _render(registry)

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(content, encoding="utf-8")

    total_anomalies = sum(len(v) for v in registry.values())
    print(f"  [Q] {total_anomalies} anomalies, {len(registry)} themes")
    print(f"  [Q] Registry: {OUT_PATH}")


if __name__ == "__main__":
    main()
