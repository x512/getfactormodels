# scripts/build_jkp_registry.py
"""This module generates the registry mappings for JKP Global Factors.

It downloads metadata from JKP's `availability.json` and saves the parsed
mappings into a generated file.
"""
import json
from pathlib import Path
import urllib.request
from urllib.error import HTTPError, URLError
# TEMP:FIXME:good enough
URL = "https://jkpfactors-data.s3.amazonaws.com/public/availability.json"
OUT_PATH = Path("src/getfactormodels/registries/_jkp.py")

print(f"  [JKP] Downloading {URL}...")

try:
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=10) as response:
        raw_body = response.read().decode('utf-8')
        data = json.loads(raw_body)
except (HTTPError, URLError) as e:
    print(f"Network or HTTP error occurred: {e}")
    raise
except json.JSONDecodeError:
    print("JSON decode error occurred.")
    raise

dropdowns = data.get("dropdown_options", {})
anomalies, themes = {}, {}

# factors and themes
for group in dropdowns.get("themes", []):
    name, opts = group.get("group"), group.get("options", [])

    if name == "Factors":
        anomalies.update({
            o["value"]: {"name": o.get("label", o["value"])}
            for o in opts if o.get("value")
        })
    elif name == "Themes":
        themes.update({
            o["value"]: {"name": o.get("label", o["value"])}
            for o in opts if o.get("value") and o["value"] != "all_themes"
        })

# regions/countries
region_map = {
    g.get("group"): [o["value"] for o in g.get("options", []) if o.get("value")]
    for g in dropdowns.get("regions", [])
}

countries = region_map.get("Countries", [])
macro_regions = region_map.get("Regions", [])
sorted_regions = sorted(countries) + sorted(macro_regions)

theme_lines = [f'    "{k}": {{"name": {v["name"]!r}}},' for k, v in sorted(themes.items())]
anomaly_lines = [f'    "{k}": {{"name": {v["name"]!r}}},' for k, v in sorted(anomalies.items())]

region_chunks = [
    f"    {', '.join(f'\"{r}\"' for r in sorted_regions[i:i+6])},"
    for i in range(0, len(sorted_regions), 6)
]


file_content = f"""# AUTO-GENERATED by scripts/build_jkp.py. Do not edit.
#
# Source:
#   {URL}
# 
# Factor data is distributed under the MIT License.

JKP_REGIONS = [
{"\n".join(region_chunks)}
]

JKP_THEMES = {{
{"\n".join(theme_lines)}
}}

JKP_FACTORS = {{
{"\n".join(anomaly_lines)}
}}
"""

# write registry file
OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
OUT_PATH.write_text(file_content, encoding="utf-8")

print(f"  [JKP] {len(anomalies)} anomalies, {len(themes)} themes, {len(sorted_regions)} regions.")
print(f"  [JKP] Registry: {OUT_PATH}")
